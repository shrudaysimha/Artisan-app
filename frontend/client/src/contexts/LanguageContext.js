export const localizeProduct = (product, lang = "en") => {
  if (!product) return product;
  const translation = PRODUCT_TRANSLATIONS[product.id]?.[lang];
  if (!translation) return product;
  return {
    ...product,
    title: translation.title || product.title,
    category: translation.category || product.category,
    craft_type: translation.craft_type || product.craft_type,
    region: translation.region || product.region,
    materials: translation.materials || product.materials,
    description: translation.description || product.description,
  };
};

const supportedLanguages = ["en", "hi", "te", "ta", "kn", "bn", "mr", "gu", "ml", "pa", "or", "ur"];
supportedLanguages.forEach((lang) => {
  if (!translations[lang]) {
    translations[lang] = translations.kn || translations.ta || translations.te || translations.hi || translations.en;
  }
});

const LanguageContext = createContext();

export const LanguageProvider = ({ children }) => {
  const [lang, setLang] = useState("en");
  const [isClient, setIsClient] = useState(false);
  const [bhashiniKey, setBhashiniKey] = useState("");
  const [bhashiniUserId, setBhashiniUserId] = useState("");
  const [bhashiniEndpoint, setBhashiniEndpoint] = useState("");

  useEffect(() => {
    setIsClient(true);
    const savedLang = localStorage.getItem("kalaa_lang");
    if (savedLang && supportedLanguages.includes(savedLang)) {
      setLang(savedLang);
    }
    const savedBhashiniKey = localStorage.getItem("bhashini_udhyat_key") || "";
    const savedBhashiniUser = localStorage.getItem("bhashini_user_id") || "";
    const savedBhashiniEp = localStorage.getItem("bhashini_endpoint") || "";
    if (savedBhashiniKey) setBhashiniKey(savedBhashiniKey);
    if (savedBhashiniUser) setBhashiniUserId(savedBhashiniUser);
    if (savedBhashiniEp) setBhashiniEndpoint(savedBhashiniEp);
  }, []);

  const changeLanguage = (newLang) => {
    setLang(newLang);
    try {
      localStorage.setItem("kalaa_lang", newLang);
    } catch (e) {
      console.warn("Could not save language to localStorage", e);
    }
    if (typeof document !== "undefined") {
      if (newLang === "ur") document.documentElement.dir = "rtl";
      else document.documentElement.dir = "ltr";
    }
  };

  const saveBhashiniConfig = (key, userId = "", endpoint = "") => {
    setBhashiniKey(key);
    setBhashiniUserId(userId);
    setBhashiniEndpoint(endpoint);
    try {
      if (key) localStorage.setItem("bhashini_udhyat_key", key);
      else localStorage.removeItem("bhashini_udhyat_key");
      if (userId) localStorage.setItem("bhashini_user_id", userId);
      if (endpoint) localStorage.setItem("bhashini_endpoint", endpoint);
    } catch (e) {
      console.warn("Could not save Bhashini config", e);
    }
  };

  const t = (key, fallback = "") => {
    const currentDict = translations[lang] || translations.en;
    if (currentDict && currentDict[key]) {
      return currentDict[key];
    }
    if (translations.en && translations.en[key]) {
      return translations.en[key];
    }
    return fallback || key;
  };

  return (
    <LanguageContext.Provider
      value={{
        lang,
        currentLang: lang,
        changeLanguage,
        setLanguage: changeLanguage,
        t,
        isClient,
        localizeProduct: (p) => localizeProduct(p, lang),
        bhashiniKey,
        bhashiniUserId,
        bhashiniEndpoint,
        saveBhashiniConfig,
        isBhashiniActive: Boolean(bhashiniKey),
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const context = useContext(LanguageContext);
  if (!context) {
    return {
      lang: "en",
      currentLang: "en",
      changeLanguage: () => { },
      setLanguage: () => { },
      t: (key, fallback = "") => fallback || key,
      isClient: false,
      localizeProduct: (p) => p,
      bhashiniKey: "",
      bhashiniUserId: "",
      bhashiniEndpoint: "",
      saveBhashiniConfig: () => { },
      isBhashiniActive: false,
    };
  }
  return context;
};
